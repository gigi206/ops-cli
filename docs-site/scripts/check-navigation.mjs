#!/usr/bin/env node
// Fails when a guide page is reachable by URL and by search but by no hand-written
// route into it. Docusaurus already throws on a link that points nowhere; nothing
// catches the opposite, a page nothing points at, which is how six configuration
// pages came to be listed in the sidebar and in no index.
//
// Four rules, each one a way a page goes missing:
//   1. every page is named in sidebars.ts (or lives under a generated directory)
//   2. every directory has an index.md, so a trimmed URL lands somewhere
//   3. every section index links every page of its own section
//   4. the guide index links every page of the site
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..');
const DOCS = join(ROOT, 'docs', 'guide');
// Directories written by a generator: their pages are listed by an autogenerated
// sidebar entry and by their own generated index, so rules 1 and 4 do not apply.
const GENERATED = ['secrets/providers'];

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.md') ? [join(dir, e.name)] : []
  );

const pages = walk(DOCS).map((p) => relative(DOCS, p).replaceAll('\\', '/')).sort();
const id = (p) => p.replace(/\.md$/, '');
const generated = (p) => GENERATED.some((g) => p.startsWith(`${g}/`));
const errors = [];

// ---- 1. listed in sidebars.ts -------------------------------------------------
const sidebars = readFileSync(join(ROOT, 'sidebars.ts'), 'utf8');
const listed = new Set([...sidebars.matchAll(/'([a-z0-9./-]+)'/g)].map((m) => m[1]));
for (const p of pages) {
  if (generated(p)) continue;
  if (!listed.has(id(p))) errors.push(`sidebars.ts does not list ${p}`);
}

// ---- 2. every directory has an index ------------------------------------------
const dirs = new Set(pages.map((p) => dirname(p)).filter((d) => d !== '.'));
for (const d of dirs) {
  if (!existsSync(join(DOCS, d, 'index.md'))) errors.push(`${d}/ has no index.md, so /docs/${d}/ is a 404`);
}

// ---- link extraction ----------------------------------------------------------
/** The set of pages one file links to, resolved to page ids. */
function linksOf(page) {
  const body = readFileSync(join(DOCS, page), 'utf8');
  const from = dirname(page);
  const out = new Set();
  for (const m of body.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1].split('#')[0];
    if (!target || /^(https?:|mailto:)/.test(target)) continue;
    const abs = relative(DOCS, resolve(DOCS, from, target)).replaceAll('\\', '/');
    for (const cand of [`${abs}.md`, join(abs, 'index.md').replaceAll('\\', '/'), abs]) {
      if (pages.includes(cand)) { out.add(cand); break; }
    }
  }
  return out;
}

// ---- 3. a section index links its own section ---------------------------------
for (const d of [...dirs].sort()) {
  const idx = `${d}/index.md`;
  const linked = linksOf(idx);
  for (const p of pages.filter((p) => dirname(p) === d && p !== idx)) {
    if (!linked.has(p)) errors.push(`${idx} does not link ${p}`);
  }
}

// ---- 4. the guide index links everything --------------------------------------
const rootLinks = linksOf('index.md');
for (const p of pages) {
  if (p === 'index.md' || generated(p)) continue;
  // a section index reached through its own section landing page counts
  if (!rootLinks.has(p)) errors.push(`index.md does not link ${p}`);
}

if (errors.length) {
  console.error(`docs navigation is incomplete (${errors.length}):`);
  for (const e of errors) console.error(`  - ${e}`);
  console.error('\nEvery page needs a route in: sidebars.ts, its section index, and index.md.');
  process.exit(1);
}
console.log(`navigation complete: ${pages.length} pages, ${dirs.size} sections`);
